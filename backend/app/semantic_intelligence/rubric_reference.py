# Minimum marks each item type can carry.
#
# Extended-response types are marked with levels of response, and a level table
# needs enough marks to build distinct bands: a 2-mark "Case Study" cannot be
# banded, which would leave the teacher with a question and no way to mark it.
# Enforced in code rather than left to the model, so it holds for every subject
# and every class.
