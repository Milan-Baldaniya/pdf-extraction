def _resolve_ao_set(subject_name: str) -> Tuple[Dict, str]:
    subject = (subject_name or "").strip().lower()
    for keywords, ao_set, family in _SUBJECT_KEYWORDS:
        if any(k in subject for k in keywords):
            return ao_set, family
    return _GENERIC_AO, "General"


def subject_family(subject_name: str) -> str:
    """Which AO family this subject resolves to. Useful for reporting."""
    return _resolve_ao_set(subject_name)[1]


def _parse_class(class_level: str) -> int:
    """Pull an integer class out of values like '10', 'Class 10', 'X'."""
    text = str(class_level or "").strip().lower()
    digits = "".join(ch for ch in text if ch.isdigit())
    if digits:
        try:
            cls = int(digits)
            if 1 <= cls <= 12:
                return cls
        except ValueError:
            pass
    # Roman numerals still appear in CBSE documents ("Class X", "Class XII").
    romans = {
        "xii": 12, "xi": 11, "ix": 9, "viii": 8, "vii": 7, "vi": 6,
        "iv": 4, "v": 5, "iii": 3, "ii": 2, "i": 1, "x": 10,
    }
    for token in sorted(romans, key=len, reverse=True):
        if f"class {token}" in text or text == token:
            return romans[token]
    return 10


# ==========================================================
# NEP STAGES
# Assessment works differently at different stages. Classes 1-5 are assessed
# with qualitative descriptors under the Holistic Progress Card, not with mark
# bands: awarding "9-10 marks" to a Class 2 child is not how CBSE/NCERT assess
# the Foundational and Preparatory stages.
# ==========================================================

STAGE_FOUNDATIONAL = "Foundational"    # Classes 1-2
STAGE_PREPARATORY = "Preparatory"      # Classes 3-5
STAGE_MIDDLE = "Middle"                # Classes 6-8
STAGE_SECONDARY = "Secondary"          # Classes 9-10
STAGE_SENIOR = "Senior Secondary"      # Classes 11-12


def nep_stage(class_level: str) -> str:
    cls = _parse_class(class_level)
    if cls <= 2:
        return STAGE_FOUNDATIONAL
    if cls <= 5:
        return STAGE_PREPARATORY
    if cls <= 8:
        return STAGE_MIDDLE
    if cls <= 10:
        return STAGE_SECONDARY
    return STAGE_SENIOR


def uses_mark_bands(class_level: str) -> bool:
    """Classes 1-5 are descriptor-based; Classes 6-12 use numeric mark bands."""
    return nep_stage(class_level) not in (STAGE_FOUNDATIONAL, STAGE_PREPARATORY)


def ao_weightings_are_official(subject_name: str, class_level: str) -> bool:
    """True only where CBSE actually published the weighting: Science,
    Mathematics and English, Classes 6-10."""
    cls = _parse_class(class_level)
    if not 6 <= cls <= 10:
        return False
    return subject_family(subject_name) in ("Science", "Mathematics", "Language") and \
        _resolve_ao_set(subject_name)[0] is not _GENERIC_AO


# Official CBSE question-paper composition for Classes 9-12 (2025-26 onwards).
_ITEM_MIX_SECONDARY_PLUS = (
    "50% competency-based questions (case-based, source-based, real-world application), "
    "20% multiple choice questions, "
    "30% constructed response (short and long answer)."
)


def item_mix_guidance(class_level: str) -> str:
    stage = nep_stage(class_level)
    if stage in (STAGE_SECONDARY, STAGE_SENIOR):
        return _ITEM_MIX_SECONDARY_PLUS
    if stage == STAGE_MIDDLE:
        return ("Favour understanding and application over recall. Include at least one "
                "case-based or real-world application item.")
    return ("Use short, concrete, activity-based tasks suited to young learners. "
            "Observation and oral evidence matter more than written answers.")


def valid_ao_codes(subject_name: str, class_level: str) -> List[str]:
    """AO codes valid for this subject and class (Maths has only AO1/AO2;
    English gains AO3 only from Class 9)."""
    cls = _parse_class(class_level)
    ao_set, _family = _resolve_ao_set(subject_name)
    codes = [code for code, (_desc, weights) in sorted(ao_set.items()) if cls in weights]
    if codes:
        return codes
    # Classes 1-5 sit outside the published tables. Fall back to the generic set
    # so young-learner rubrics still carry a cognitive label.
    return [code for code, (_desc, weights) in sorted(_GENERIC_AO.items()) if 6 in weights]


def build_ao_block(subject_name: str, class_level: str) -> str:
    """Render the AO table for injection into the Agent 4 prompt."""
    cls = _parse_class(class_level)
    ao_set, family = _resolve_ao_set(subject_name)
    official = ao_weightings_are_official(subject_name, class_level)

    lines = []
    for code, (desc, weights) in sorted(ao_set.items()):
        if cls not in weights:
            continue
        lines.append(f"- {code} ({weights[cls]}% of marks): {desc}")

    if not lines:
        # Classes 1-5: describe the objectives without percentage targets.
        for code in valid_ao_codes(subject_name, class_level):
            desc = _GENERIC_AO[code][0]
            lines.append(f"- {code}: {desc}")
        header = (f"Assessment objectives for the {nep_stage(class_level)} stage "
                  f"({family}). No fixed percentage weightings apply at this stage.")
        return header + "\n" + "\n".join(lines)

    if official:
        header = f"Official CBSE assessment objectives and weightings ({family}, Class {cls}):"
    else:
        header = (f"Assessment objectives for {family}, Class {cls}. NOTE: CBSE published "
                  f"weightings only for Science, Mathematics and English in Classes 6-10. "
                  f"The percentages below are derived as a reasonable target, not official CBSE figures:")
    return header + "\n" + "\n".join(lines)


