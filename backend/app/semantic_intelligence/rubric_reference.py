"""CBSE assessment reference data for rubric generation.

Everything in this module is *reference data*, not LLM output. It encodes the
CBSE Assessment Framework (British Council / AlphaPlus, March 2021):

  - Assessment Objectives (AOs) and their official percentage weightings,
    which differ per subject and per class.
  - The levels-of-response band structure: level count, mark bands, the
    controlled quality ladder, and the mandatory Level 0 "Nothing to reward".

Level descriptors are built here rather than generated by the LLM so that every
item of the same (marks, level-count) shape carries byte-identical bands. That
is what makes marking comparable across chapters, which is the entire point of
a standardised mark scheme.
"""

from __future__ import annotations

from typing import Dict, List, Tuple

# ==========================================================
# ASSESSMENT OBJECTIVES
# Source: CBSE Assessment Framework pp.16 (English), 66 (Maths), 144 (Science)
# ==========================================================

# CBSE published this AO framework for Classes 6-10 only, and only for Science,
# Mathematics and English. Weightings for Classes 11-12 are DERIVED by carrying
# the published Class 9-10 values forward; they are flagged as such via
# ao_weightings_are_official() so nothing downstream presents them as CBSE fact.
_DERIVED_SENIOR = (11, 12)


def _extend_senior(weights: Dict[int, str]) -> Dict[int, str]:
    """Carry the published Class 10 weighting forward to Classes 11-12."""
    if 10 not in weights:
        return dict(weights)
    extended = dict(weights)
    for cls in _DERIVED_SENIOR:
        extended[cls] = weights[10]
    return extended


