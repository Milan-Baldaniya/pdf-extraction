# ==========================================================
# LEVELS OF RESPONSE - BAND CONSTRUCTION
# Source: CBSE Assessment Framework pp.60, 63
# ==========================================================

# Controlled quality ladder. Each entry is
#   (quality_band, teacher-facing label, performance bullet, evidence bullet)
# The performance bullet takes the item's skill_phrase so the band reads as
# concept-specific prose while the progression vocabulary stays fixed.
_LADDER: List[Tuple[str, str, str, str]] = [
    ("Perceptive", "Excellent",
     "A perceptive and sustained analysis of {skill_phrase}",
     "Well-selected references from the material used as an integral part of the response"),
    ("Clear", "Good",
     "A clear, well-developed explanation of {skill_phrase}",
     "A wide range of relevant references used to support the response"),
    ("Generally Clear", "Fair",
     "A generally clear explanation of {skill_phrase}",
     "Relevant references used to support the explanation"),
    ("Straightforward", "Needs Improvement",
     "Some straightforward comment on {skill_phrase}",
     "Some detail used, beginning to support the comments"),
    ("Limited", "Beginning",
     "Limited awareness of {skill_phrase}",
     "Limited use of supporting detail"),
]


def level_count_for_marks(marks: int) -> int:
    """CBSE bands must be awardable. A 3-mark item cannot carry five levels."""
    if marks <= 2:
        return 0          # point-based territory, no levels
    if marks <= 4:
        return 3
    if marks <= 6:
        return 4
    return 5


def _mark_bands(marks: int, levels: int) -> List[Tuple[int, int]]:
    """Split 1..marks into `levels` contiguous, non-overlapping bands.

    Returned lowest-band-first. The top band always ends exactly at `marks`,
    and every mark from 1 to `marks` falls in exactly one band.
    """
    base, remainder = divmod(marks, levels)
    sizes = [base + (1 if i < remainder else 0) for i in range(levels)]
    bands: List[Tuple[int, int]] = []
    low = 1
    for size in sizes:
        bands.append((low, low + size - 1))
        low += size
    return bands


# Holistic Progress Card style scale for Classes 1-5. Descriptor-based, with no
# marks: NEP and the HPC assess the Foundational and Preparatory stages
# qualitatively rather than numerically.
_HPC_LADDER: List[Tuple[str, str, str]] = [
    ("Proficient", "Proficient", "Consistently and independently demonstrates {skill_phrase}"),
    ("Progressing", "Progressing", "Demonstrates {skill_phrase} with occasional support"),
    ("Beginner", "Beginner", "Beginning to demonstrate {skill_phrase}; needs regular support"),
]


def build_hpc_descriptors(skill_phrase: str) -> List[dict]:
    """Qualitative descriptor scale for Classes 1-5. Carries no marks."""
    return [
        {
            "level": len(_HPC_LADDER) - offset,
            "quality_band": quality,
            "display_label": label,
            "descriptors": [template.format(skill_phrase=skill_phrase)],
            "mark_low": 0,
            "mark_high": 0,
        }
        for offset, (quality, label, template) in enumerate(_HPC_LADDER)
    ]


def build_level_descriptors(marks: int, skill_phrase: str, class_level: str = "") -> List[dict]:
    """Build the CBSE levels-of-response table for an item.

    Descends from the highest level to Level 0 ("Nothing to reward", 0 marks),
    exactly as the framework exemplars on pp.60 and 63 do. For Classes 1-5 the
    numeric bands are replaced by the qualitative HPC scale.
    """
    if class_level and not uses_mark_bands(class_level):
        return build_hpc_descriptors(skill_phrase)

    levels = level_count_for_marks(marks)
    if levels == 0:
        return []

    # Take the top `levels` rungs of the ladder so that short items still start
    # at "Perceptive" and degrade to "Limited".
    rungs = _LADDER[:levels]
    bands = _mark_bands(marks, levels)  # lowest first

    descriptors: List[dict] = []
    # rungs[0] is the best band and pairs with the highest mark band.
    for offset, (quality, label, performance, evidence) in enumerate(rungs):
        low, high = bands[levels - 1 - offset]
        descriptors.append({
            "level": levels - offset,
            "quality_band": quality,
            "display_label": label,
            "descriptors": [
                performance.format(skill_phrase=skill_phrase),
                evidence,
            ],
            "mark_low": low,
            "mark_high": high,
        })

    descriptors.append({
        "level": 0,
        "quality_band": "Nothing to Reward",
        "display_label": "No Credit",
        "descriptors": ["Nothing to reward"],
        "mark_low": 0,
        "mark_high": 0,
    })
    return descriptors


