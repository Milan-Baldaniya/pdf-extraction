_CRITERION_QUALITY: List[Tuple[str, str, str]] = [
    ("Perceptive", "Excellent", "Thorough, accurate and consistent"),
    ("Clear", "Good", "Clear and largely accurate"),
    ("Generally Clear", "Fair", "Generally sound, with minor gaps"),
    ("Straightforward", "Needs Improvement", "Partial, with notable gaps"),
    ("Limited", "Beginning", "Minimal"),
]


def build_criterion_descriptors(criterion: str, weight_marks: int) -> List[dict]:
    """Build the level descriptors for one analytical criterion."""
    levels = max(2, min(level_count_for_marks(weight_marks) or 2, 5))
    focus = CRITERION_FOCUS.get(criterion, "performance against this criterion")
    rungs = _CRITERION_QUALITY[:levels]
    bands = _mark_bands(weight_marks, levels)

    descriptors: List[dict] = []
    for offset, (quality, label, adjective) in enumerate(rungs):
        low, high = bands[levels - 1 - offset]
        descriptors.append({
            "level": levels - offset,
            "quality_band": quality,
            "display_label": label,
            "descriptors": [f"{adjective} {focus}."],
            "mark_low": low,
            "mark_high": high,
        })

    descriptors.append({
        "level": 0,
        "quality_band": "Nothing to Reward",
        "display_label": "No Credit",
        "descriptors": ["Nothing to reward"],
        "mark_low": 0,
        "mark_high": 0,
    })
    return descriptors
